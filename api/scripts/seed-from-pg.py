"""Generate migrations/0008_seed_data.sql: the reference rows the Supabase migrations seed (content, inventory,
practice questions, feature flags, settings, starter mentors and sessions), converted for D1.

Needs the throwaway Postgres with every supabase/migrations file applied (see README).
Usage (from api/): python scripts/seed-from-pg.py > migrations/0008_seed_data.sql
User-bound rows (admins, profiles, memberships, audit logs, outbox) are deliberately excluded.
"""
import json
import shlex
import subprocess
import sys
from datetime import datetime, timezone

PSQL = sys.argv[1] if len(sys.argv) > 1 else "-h localhost -p 55432 -U postgres -d gwmb"
# Parent tables before children (foreign keys).
TABLES = [
    ("feature_flags", "key"), ("app_settings", None), ("career_practice_questions", "id"), ("marketplace_inventory", "id"),
    ("content_items", "slug"), ("mentors", "id"), ("mentor_operations", "mentor_id"), ("mentorship_sessions", "id"),
    ("mentorship_session_mentors", "session_id"),
]
USER_COLUMNS = {"created_by", "updated_by", "added_by", "reviewed_by", "confirmed_by", "actor_user_id"}


def q(sql: str):
    out = subprocess.run(["psql", *shlex.split(PSQL), "-tA", "-c", sql], capture_output=True, text=True, check=True).stdout.strip()
    return json.loads(out) if out else None


def literal(value, kind: str) -> str:
    if value is None:
        return "null"
    if kind == "boolean":
        return "1" if value else "0"
    if kind in ("jsonb", "json", "ARRAY"):
        text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    elif kind == "timestamp with time zone":
        text = datetime.fromisoformat(value).astimezone(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")
    elif kind in ("integer", "bigint", "smallint", "numeric", "real", "double precision"):
        return str(value)
    else:
        text = str(value)
    return "'" + text.replace("'", "''") + "'"


print("-- Generated by api/scripts/seed-from-pg.py: reference data seeded by the Supabase migrations.")
print("-- `insert or ignore` keeps this safe to apply to a database that already has some of these rows.\n")
for table, _key in TABLES:
    kinds = {c["c"]: c["t"] for c in q(f"select json_agg(json_build_object('c',column_name,'t',data_type)) from information_schema.columns where table_schema='public' and table_name='{table}'")}
    rows = q(f"select json_agg(t) from public.{table} t") or []
    if not rows:
        continue
    cols = [c for c in rows[0].keys() if c not in USER_COLUMNS]
    print(f"-- {table}: {len(rows)} row(s)")
    for row in rows:
        values = ", ".join(literal(row[c], kinds[c]) for c in cols)
        print(f"insert or ignore into {table} ({', '.join(cols)}) values ({values});")
    print()
