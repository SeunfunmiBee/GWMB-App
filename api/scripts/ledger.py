"""Write api/PORTING_LEDGER.md: server logic from the Supabase schema that the Worker must re-implement.

Needs the same throwaway Postgres as pg-to-d1.py (all supabase/migrations applied).
Usage (from repo root): python api/scripts/ledger.py > api/PORTING_LEDGER.md
"""
import glob
import json
import re
import shlex
import subprocess
import sys

PSQL = sys.argv[1] if len(sys.argv) > 1 else "-h localhost -p 55432 -U postgres -d gwmb"
MIGRATIONS = sorted(glob.glob("supabase/migrations/*.sql"))


def q(sql: str) -> list:
    out = subprocess.run(["psql", *shlex.split(PSQL), "-tA", "-c", sql], capture_output=True, text=True, check=True).stdout.strip()
    return json.loads(out) if out and out != "" else []


def defined_in(name: str) -> str:
    hits = [m for m in MIGRATIONS if re.search(rf"function\s+public\.{name}\s*\(", open(m, encoding="utf-8").read(), re.I)]
    return hits[-1].split("/")[-1].split("\\")[-1] if hits else "?"


def client_rpcs() -> set[str]:
    names: set[str] = set()
    for path in glob.glob("src/**/*.ts*", recursive=True):
        names.update(re.findall(r"\.rpc\(['\"]([a-z_]+)", open(path, encoding="utf-8").read()))
    return names


def cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


rpcs = client_rpcs()
funcs = q("""select json_agg(json_build_object('name',p.proname,'args',pg_get_function_identity_arguments(p.oid),
  'ret',pg_get_function_result(p.oid),'definer',p.prosecdef,'trigger',p.prorettype='trigger'::regtype) order by p.proname)
  from pg_proc p where p.pronamespace='public'::regnamespace""")
triggers = q("""select json_agg(json_build_object('table',tgrelid::regclass::text,'name',tgname,'fn',p.proname,
  'def',pg_get_triggerdef(t.oid)) order by tgrelid::regclass::text, tgname)
  from pg_trigger t join pg_proc p on p.oid=t.tgfoid
  where not tgisinternal and tgrelid::regclass::text not like 'storage.%' and p.proname <> 'set_updated_at'""")
policies = q("""select json_agg(json_build_object('table',tablename,'name',policyname,'cmd',cmd,'roles',roles,'using',qual,'check',with_check)
  order by tablename, cmd, policyname) from pg_policies where schemaname='public'""")

print("# Porting ledger: Supabase server logic → Worker\n")
print("Generated by `api/scripts/ledger.py` from the final Supabase schema. Each item below must exist in the Worker")
print("(with a test) before the matching app code moves off Supabase in Phase 3. Read the SQL body in the listed migration.\n")

print("## 1. Schema rules D1 cannot enforce\n")
print("- `mentorship_sessions.notification_channels` ⊆ {in_app, push, email}: validate on write.")
print("- `mentorship_sessions.distribution_surfaces` ⊆ {mentorship, learn, home, related_courses}: validate on write.")
print("- `chapter_admins.created_by`, `local_activities.created_by`: set to the caller's user id (was `auth.uid()` default).")
print("- `marketplace_inventory.career_areas` / `readiness_gaps`: GIN indexes dropped; filter JSON arrays in the Worker.")
print("- `membership_records`: the normalized identifier/email lookup index used SQL functions; store normalized values from the Worker.")
print("- Scheduled job `gwmb-notification-dispatch` (pg_cron, every minute) becomes a Worker Cron Trigger.\n")

print(f"## 2. Client RPCs ({sum(1 for f in funcs if f['name'] in rpcs)}): become API endpoints\n")
print("| Function | Arguments | Returns | Definer | Defined in |\n| --- | --- | --- | --- | --- |")
for f in funcs:
    if f["name"] in rpcs:
        print(f"| `{f['name']}` | {cell(f['args'])} | {cell(f['ret'])} | {'yes' if f['definer'] else ''} | {defined_in(f['name'])} |")

print(f"\n## 3. Triggers with business logic ({len(triggers)}): `updated_at` triggers are already SQLite triggers\n")
print("| Table | Trigger | Function | Fires |\n| --- | --- | --- | --- |")
for t in triggers:
    fires = re.search(r"(BEFORE|AFTER) (.*?) ON", t["def"])
    print(f"| `{t['table']}` | {t['name']} | `{t['fn']}` ({defined_in(t['fn'])}) | {cell(fires.group(1) + ' ' + fires.group(2) if fires else '')} |")

helpers = [f for f in funcs if f["name"] not in rpcs and not f["trigger"]]
print(f"\n## 4. Helper functions ({len(helpers)}): port only where an RPC or trigger above uses them\n")
print(", ".join(f"`{f['name']}`" for f in helpers))

print(f"\n## 5. Access rules: former RLS policies ({len(policies)})\n")
print("No policy = no direct client access (only through RPCs/service code). `true` = any caller in the listed roles.\n")
print("| Table | Operation | Roles | Row may be read/changed when | New row must satisfy |\n| --- | --- | --- | --- | --- |")
for p in policies:
    roles = p["roles"] if isinstance(p["roles"], str) else ",".join(p["roles"])
    print(f"| `{p['table']}` | {p['cmd']} | {cell(roles.strip('{}'))} | {cell(p['using'])} | {cell(p['check'])} |")
